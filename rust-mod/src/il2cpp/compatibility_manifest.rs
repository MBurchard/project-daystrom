#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Requirement {
    Required,
    Optional,
}

#[derive(Clone, Copy, Debug)]
#[allow(dead_code)] // Full signatures are consumed by the standalone dump checker before runtime validation uses them.
pub enum MemberSpec {
    Class,
    Method {
        names: &'static [&'static str],
        match_all: bool,
        return_type: &'static str,
        parameter_types: &'static [&'static str],
        is_static: bool,
    },
    Field {
        names: &'static [&'static str],
        match_all: bool,
        field_type: &'static str,
    },
}

#[derive(Clone, Copy, Debug)]
pub struct SymbolSpec {
    pub feature: &'static str,
    pub assemblies: &'static [&'static str],
    pub namespace: &'static str,
    pub class_name: &'static str,
    pub requirement: Requirement,
    pub member: MemberSpec,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum FeatureStatus {
    Ready,
    Degraded,
    Disabled,
}

impl FeatureStatus {
    pub const fn label(self) -> &'static str {
        match self {
            Self::Ready => "ready",
            Self::Degraded => "degraded",
            Self::Disabled => "disabled",
        }
    }
}

impl fmt::Display for FeatureStatus {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.label())
    }
}

#[derive(Debug, Default)]
pub struct FeatureResult {
    pub missing_required: Vec<String>,
    pub missing_optional: Vec<String>,
}

impl FeatureResult {
    pub fn status(&self) -> FeatureStatus {
        if !self.missing_required.is_empty() {
            FeatureStatus::Disabled
        } else if !self.missing_optional.is_empty() {
            FeatureStatus::Degraded
        } else {
            FeatureStatus::Ready
        }
    }
}

pub fn assess(mut symbol_available: impl FnMut(&SymbolSpec) -> bool) -> BTreeMap<&'static str, FeatureResult> {
    let mut results = FEATURES
        .iter()
        .map(|feature| (*feature, FeatureResult::default()))
        .collect::<BTreeMap<_, _>>();

    for symbol in SYMBOLS {
        if symbol_available(symbol) {
            continue;
        }
        let result = results.entry(symbol.feature).or_default();
        match symbol.requirement {
            Requirement::Required => result.missing_required.push(symbol.display_name()),
            Requirement::Optional => result.missing_optional.push(symbol.display_name()),
        }
    }

    results
}

pub fn matches_names(names: &[&str], match_all: bool, mut predicate: impl FnMut(&str) -> bool) -> bool {
    if match_all {
        names.iter().all(|name| predicate(name))
    } else {
        names.iter().any(|name| predicate(name))
    }
}

impl SymbolSpec {
    pub fn display_name(&self) -> String {
        let class = if self.namespace.is_empty() {
            self.class_name.to_string()
        } else {
            format!("{}.{}", self.namespace, self.class_name)
        };
        match self.member {
            MemberSpec::Class => class,
            MemberSpec::Method { names, .. } => format!("{class}.{}", names.join("|")),
            MemberSpec::Field { names, .. } => format!("{class}.{}", names.join("|")),
        }
    }
}

const fn class(
    feature: &'static str,
    assemblies: &'static [&'static str],
    namespace: &'static str,
    class_name: &'static str,
    requirement: Requirement,
) -> SymbolSpec {
    SymbolSpec {
        feature,
        assemblies,
        namespace,
        class_name,
        requirement,
        member: MemberSpec::Class,
    }
}

#[allow(clippy::too_many_arguments)] // Declarative manifest builder; grouping these values would obscure entries.
const fn method(
    feature: &'static str,
    assemblies: &'static [&'static str],
    namespace: &'static str,
    class_name: &'static str,
    names: &'static [&'static str],
    return_type: &'static str,
    parameter_types: &'static [&'static str],
    is_static: bool,
    requirement: Requirement,
) -> SymbolSpec {
    SymbolSpec {
        feature,
        assemblies,
        namespace,
        class_name,
        requirement,
        member: MemberSpec::Method {
            names,
            match_all: false,
            return_type,
            parameter_types,
            is_static,
        },
    }
}

const fn field(
    feature: &'static str,
    assemblies: &'static [&'static str],
    namespace: &'static str,
    class_name: &'static str,
    names: &'static [&'static str],
    field_type: &'static str,
    requirement: Requirement,
) -> SymbolSpec {
    SymbolSpec {
        feature,
        assemblies,
        namespace,
        class_name,
        requirement,
        member: MemberSpec::Field { names, match_all: false, field_type },
    }
}

#[allow(clippy::too_many_arguments)] // Declarative manifest builder; grouping these values would obscure entries.
const fn methods(
    feature: &'static str,
    assemblies: &'static [&'static str],
    namespace: &'static str,
    class_name: &'static str,
    names: &'static [&'static str],
    return_type: &'static str,
    parameter_types: &'static [&'static str],
    is_static: bool,
    requirement: Requirement,
) -> SymbolSpec {
    let mut spec = method(
        feature,
        assemblies,
        namespace,
        class_name,
        names,
        return_type,
        parameter_types,
        is_static,
        requirement,
    );
    if let MemberSpec::Method { ref mut match_all, .. } = spec.member {
        *match_all = true;
    }
    spec
}

const fn fields(
    feature: &'static str,
    assemblies: &'static [&'static str],
    namespace: &'static str,
    class_name: &'static str,
    names: &'static [&'static str],
    field_type: &'static str,
    requirement: Requirement,
) -> SymbolSpec {
    let mut spec = field(feature, assemblies, namespace, class_name, names, field_type, requirement);
    if let MemberSpec::Field { ref mut match_all, .. } = spec.member {
        *match_all = true;
    }
    spec
}

